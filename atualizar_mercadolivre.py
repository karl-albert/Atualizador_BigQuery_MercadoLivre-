def obter_fator_sazonal_diario(d):
    """
    Curvas de Sazonalidade Diária Calibradas (2025 e 2026):
    - Novembro: Esquenta Black November (+12%), Black Week (+30%), Black Friday (+95%), Black Weekend (+40%).
    - Dezembro: Cyber Monday (+55%), Ritmo Natal (+28%), 2ª Parcela 13º + Corrida de Natal (+80%), Pós-Natal (-8%).
    - Demais Meses: Ímpares (+5%), Pares (-3%).
    """
    ano = d.year
    mes = d.month
    dia = d.day

    # --- ANO 2025 ---
    if ano == 2025:
        if mes == 11:
            if dia == 28:
                return 1.95       # Black Friday + 1ª Parcela do 13º Salário
            elif dia in (29, 30):
                return 1.40       # Fim de semana Black Weekend (+40%)
            elif 24 <= dia <= 27:
                return 1.30       # Black Week (+30%)
            else:
                return 1.12       # Black November esquenta (+12%)
        elif mes == 12:
            if dia == 1:
                return 1.55       # Cyber Monday (+55%)
            elif 19 <= dia <= 24:
                return 1.80       # 2ª Parcela 13º + Clímax de Natal (+80%)
            elif 2 <= dia <= 18:
                return 1.28       # Compras de Natal com 1ª parcela (+28%)
            else:
                return 0.92       # Pós-Natal (-8%)

    # --- ANO 2026 ---
    elif ano == 2026:
        if mes == 11:
            if dia == 27:
                return 1.95       # Black Friday 2026 (+95%)
            elif dia in (28, 29):
                return 1.40       # Black Weekend 2026 (+40%)
            elif dia == 30:
                return 1.65       # Cyber Monday + Limite 1ª Parc 13º (+65%)
            elif 23 <= dia <= 26:
                return 1.30       # Black Week 2026 (+30%)
            else:
                return 1.12       # Black November esquenta (+12%)
        elif mes == 12:
            if 18 <= dia <= 24:
                return 1.80       # 2ª Parcela 13º (18/12) + Corrida de Natal (+80%)
            elif 1 <= dia <= 17:
                return 1.28       # Compras de Natal (+28%)
            else:
                return 0.92       # Pós-Natal (-8%)

    # --- DEMAIS MESES PADRÃO ---
    if mes % 2 != 0:
        return 1.05  # Meses Ímpares: +5%
    else:
        return 0.97  # Meses Pares: -3%

_CACHE_MEDIAS_6M = {}

def obter_medias_historicas_6m(data_referencia, client=None):
    """
    Calcula a media diaria de vendas de cada produto nos ultimos 6 meses anteriores ao mes atual.
    Ordem de resolucao:
    1. Cache em memoria
    2. Arquivo Parquet local (se disponivel na maquina)
    3. Consulta direta no BigQuery (em nuvem, ex: GitHub Actions)
    4. Dicionario de fallback embutido com as medias exatas dos 250 produtos
    """
    global _CACHE_MEDIAS_6M
    chave = (data_referencia.year, data_referencia.month)
    if chave in _CACHE_MEDIAS_6M:
        return _CACHE_MEDIAS_6M[chave]
        
    medias_prod = {}
    medias_cat = {}
    
    # 1. Tentar ler do Parquet local
    if os.path.exists(LOCAL_PARQUET):
        try:
            df_hist = pd.read_parquet(LOCAL_PARQUET)
            df_hist["data_dt"] = pd.to_datetime(df_hist["data"]).dt.date
            df_hist["qtd"] = pd.to_numeric(df_hist["qtd_vendas_estimadas_dia"].astype(str).str.replace(",", "."), errors="coerce")
            
            p_dia = data_referencia.replace(day=1)
            u_dia = p_dia - timedelta(days=1)
            m_ini = p_dia.month - 6
            a_ini = p_dia.year
            if m_ini <= 0:
                m_ini += 12
                a_ini -= 1
            ini_6m = date(a_ini, m_ini, 1)
            
            sub = df_hist[(df_hist["data_dt"] >= ini_6m) & (df_hist["data_dt"] <= u_dia)]
            if not sub.empty:
                medias_prod = sub.groupby(["categoria", "titulo_produto"])["qtd"].mean().to_dict()
                medias_cat = sub.groupby("categoria")["qtd"].mean().to_dict()
                logger.info(f"Medias de 6 meses calculadas via Parquet local ({len(medias_prod)} produtos).")
        except Exception as e:
            logger.warning(f"Aviso ao ler medias de 6 meses do Parquet: {e}")
            
    # 2. Se nao encontrou no Parquet (ex: GitHub Actions), consultar BigQuery
    if not medias_prod:
        try:
            if client is None:
                client = obter_cliente_bigquery()
            if client:
                p_dia = data_referencia.replace(day=1)
                u_dia = p_dia - timedelta(days=1)
                m_ini = p_dia.month - 6
                a_ini = p_dia.year
                if m_ini <= 0:
                    m_ini += 12
                    a_ini -= 1
                ini_6m = date(a_ini, m_ini, 1)
                
                tabela_completa = f"{GCP_PROJECT_ID}.{DATASET_ID}.{TABELA_ID}"
                q = f"""
                SELECT categoria, titulo_produto, AVG(qtd_vendas_estimadas_dia) as media_qtd
                FROM `{tabela_completa}`
                WHERE data >= '{ini_6m.strftime("%Y-%m-%d")}'
                  AND data <= '{u_dia.strftime("%Y-%m-%d")}'
                GROUP BY categoria, titulo_produto
                """
                df_bq = client.query(q).to_dataframe()
                if not df_bq.empty:
                    medias_prod = {(r["categoria"], r["titulo_produto"]): float(r["media_qtd"]) for _, r in df_bq.iterrows()}
                    medias_cat = df_bq.groupby("categoria")["media_qtd"].mean().to_dict()
                    logger.info(f"Medias de 6 meses calculadas via BigQuery ({len(medias_prod)} produtos).")
        except Exception as e:
            logger.warning(f"Aviso ao calcular medias via BigQuery: {e}")

    # 3. Fallback seguro embutido
    if not medias_prod:
        logger.info("Utilizando medias historicas do dicionario embutido de fallback.")
        medias_prod = {tuple(k.split("|||")): float(v) for k, v in MEDIAS_FALLBACK_250.items()}
        cat_sums = {}
        cat_counts = {}
        for (c, _), v in medias_prod.items():
            cat_sums[c] = cat_sums.get(c, 0.0) + v
            cat_counts[c] = cat_counts.get(c, 0) + 1
        medias_cat = {c: cat_sums[c] / cat_counts[c] for c in cat_sums}

    _CACHE_MEDIAS_6M[chave] = (medias_prod, medias_cat)
    return medias_prod, medias_cat


_CACHE_BONUS_MES_ANTERIOR = {}

def obter_bonus_mes_anterior(data_referencia, client=None):
    """
    Calcula o bonus de ranking do mes anterior inteiro por categoria:
    - 1o colocado em Quantidade: +10% (0.10)
    - 2o colocado em Faturamento: +15% (0.15)
    - 3o e 4o colocados em Quantidade: +20% (0.20)
    """
    global _CACHE_BONUS_MES_ANTERIOR
    chave = (data_referencia.year, data_referencia.month)
    if chave in _CACHE_BONUS_MES_ANTERIOR:
        return _CACHE_BONUS_MES_ANTERIOR[chave]
        
    bonus_map = {}
    
    # 1. Tentar ler do Parquet local
    if os.path.exists(LOCAL_PARQUET):
        try:
            df_hist = pd.read_parquet(LOCAL_PARQUET)
            df_hist['preco_num'] = (
                df_hist['preco_atual']
                .astype(str)
                .str.replace('.', '', regex=False)
                .str.replace(',', '.', regex=False)
                .astype(float)
            )
            df_hist['qtd_num'] = pd.to_numeric(
                df_hist['qtd_vendas_estimadas_dia'].astype(str).str.replace(',', '.'),
                errors='coerce'
            )
            
            p_dia = data_referencia.replace(day=1)
            u_dia_ant = p_dia - timedelta(days=1)
            ano_ant = u_dia_ant.year
            mes_ant = u_dia_ant.month
            
            df_prev = df_hist[(df_hist['ano'] == ano_ant) & (df_hist['mes'] == mes_ant)]
            if not df_prev.empty:
                for cat, cdf in df_prev.groupby('categoria'):
                    q_top = cdf.groupby('titulo_produto')['qtd_num'].sum().sort_values(ascending=False)
                    fat_top = (cdf['qtd_num'] * cdf['preco_num']).groupby(cdf['titulo_produto']).sum().sort_values(ascending=False)
                    
                    p_q1 = q_top.index[0] if len(q_top) >= 1 else None
                    p_f2 = fat_top.index[1] if len(fat_top) >= 2 else None
                    p_q3 = q_top.index[2] if len(q_top) >= 3 else None
                    p_q4 = q_top.index[3] if len(q_top) >= 4 else None
                    
                    if p_q1:
                        bonus_map[(cat, p_q1)] = max(bonus_map.get((cat, p_q1), 0.0), 0.10)
                    if p_f2:
                        bonus_map[(cat, p_f2)] = max(bonus_map.get((cat, p_f2), 0.0), 0.15)
                    if p_q3:
                        bonus_map[(cat, p_q3)] = max(bonus_map.get((cat, p_q3), 0.0), 0.20)
                    if p_q4:
                        bonus_map[(cat, p_q4)] = max(bonus_map.get((cat, p_q4), 0.0), 0.20)
                logger.info(f"Bonus do mes anterior calculados via Parquet local ({len(bonus_map)} produtos).")
        except Exception as e:
            logger.warning(f"Aviso ao calcular bonus do mes anterior via Parquet: {e}")
            
    # 2. Se nao encontrou no Parquet, consultar BigQuery
    if not bonus_map:
        try:
            if client is None:
                client = obter_cliente_bigquery()
            if client:
                p_dia = data_referencia.replace(day=1)
                u_dia_ant = p_dia - timedelta(days=1)
                ini_ant = p_dia.replace(month=u_dia_ant.month, year=u_dia_ant.year, day=1)
                tabela_completa = f"{GCP_PROJECT_ID}.{DATASET_ID}.{TABELA_ID}"
                q = f"""
                WITH prev_month AS (
                  SELECT categoria, titulo_produto, 
                         SUM(qtd_vendas_estimadas_dia) as total_qtd,
                         SUM(qtd_vendas_estimadas_dia * CAST(REPLACE(REPLACE(preco_atual, '.', ''), ',', '.') AS FLOAT64)) as total_fat
                  FROM `{tabela_completa}`
                  WHERE data >= '{ini_ant.strftime("%Y-%m-%d")}'
                    AND data <= '{u_dia_ant.strftime("%Y-%m-%d")}'
                  GROUP BY categoria, titulo_produto
                ),
                ranked AS (
                  SELECT *,
                         ROW_NUMBER() OVER(PARTITION BY categoria ORDER BY total_qtd DESC) as rank_qtd,
                         ROW_NUMBER() OVER(PARTITION BY categoria ORDER BY total_fat DESC) as rank_fat
                  FROM prev_month
                )
                SELECT categoria, titulo_produto, rank_qtd, rank_fat
                FROM ranked
                WHERE rank_qtd IN (1, 3, 4) OR rank_fat = 2
                """
                df_b = client.query(q).to_dataframe()
                for _, r in df_b.iterrows():
                    c = r["categoria"]
                    t = r["titulo_produto"]
                    rq = int(r["rank_qtd"])
                    rf = int(r["rank_fat"])
                    if rq == 1:
                        bonus_map[(c, t)] = max(bonus_map.get((c, t), 0.0), 0.10)
                    if rf == 2:
                        bonus_map[(c, t)] = max(bonus_map.get((c, t), 0.0), 0.15)
                    if rq in (3, 4):
                        bonus_map[(c, t)] = max(bonus_map.get((c, t), 0.0), 0.20)
                logger.info(f"Bonus do mes anterior calculados via BigQuery ({len(bonus_map)} produtos).")
        except Exception as e:
            logger.warning(f"Aviso ao calcular bonus do mes anterior via BigQuery: {e}")

    # 3. Fallback seguro embutido
    if not bonus_map:
        logger.info("Utilizando bonus do mes anterior do dicionario embutido de fallback.")
        bonus_map = {tuple(k.split("|||")): float(v) for k, v in BONUS_FALLBACK_20.items()}

    _CACHE_BONUS_MES_ANTERIOR[chave] = bonus_map
    return bonus_map

